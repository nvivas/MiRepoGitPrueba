# Ejemplos del uso de la función print

print("Hola, mundo!") # Imprime una cadena de texto

# Imprimir múltiples elementos separados por un espacio
print("La suma de 2 y 3 es:", 2 + 3)

# Usar el parámetro sep para cambiar el separador
print("a", "b", "c", sep="-")

# Usar el parámetro end para cambiar el final de línea
print("Esto se imprimirá", end=" ")
print("en la misma línea")

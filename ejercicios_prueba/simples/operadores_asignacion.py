# Asignación simple (=)
x: int = 10  # Asigna 10 a x
print("x = ", x)  # Resultado: 10

# Asignación por adición (+=)
x += 5  # Equivale a x = x + 5
print("x += 5: ", x)  # Resultado: 15

# Asignación por resta (-=)
x -= 3  # Equivale a x = x - 3
print("x -= 3: ", x)  # Resultado: 12

# Asignación por multiplicación (*=)
x *= 2  # Equivale a x = x * 2
print("x *= 2: ", x)  # Resultado: 24

# Asignación por división (/=)
x /= 4  # Equivale a x = x / 4
print("x /= 4: ", x)  # Resultado: 6.0

# Asignación por división entera (//=)
x //= 2  # Equivale a x = x // 2
print("x //= 2: ", x)  # Resultado: 3.0

# Asignación por módulo (%=)
x %= 2  # Equivale a x = x % 2
print("x %= 2: ", x)  # Resultado: 1.0

# Asignación por exponenciación (**=)
x **= 3  # Equivale a x = x ** 3
print("x **= 3: ", x)  # Resultado: 1.0

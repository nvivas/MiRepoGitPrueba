# Operador +: Concatenación de cadenas
cadena1: str = "Hola, "
cadena2: str = "mundo!"
print(cadena1 + cadena2) # Resultado: "Hola, mundo!"

# Operador *: Repetición de cadenas
repetir: str = "Hola! "
print(repetir * 3) # Resultado: "Hola! Hola! Hola! "

# Operador in: Verificar si una cadena está en otra
frase: str = "El cielo es azul"
print("cielo" in frase) # Resultado: True
print("sol" in frase) # Resultado: False

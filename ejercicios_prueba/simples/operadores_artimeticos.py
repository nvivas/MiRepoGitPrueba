# Suma (+)
a: int = 10
b: int = 5
print("Suma: ", a + b)  # Resultado: 15

# Resta (-)
print("Resta: ", a - b)  # Resultado: 5

# Multiplicación (*)
print("Multiplicación: ", a * b)  # Resultado: 50

# División (/)
print("División: ", a / b)  # Resultado: 2.0

# División entera (//)
print("División entera: ", a // b)  # Resultado: 2

# Módulo (%)
print("Módulo: ", a % b)  # Resultado: 0

# Exponenciación (**)
print("Exponenciación: ", a ** b)  # Resultado: 100000

# Precedencia de operadores
print("Precedencia: ", a + b * 2)  # Resultado: 20 (b * 2 se evalúa primero)

# Uso de paréntesis para alterar la precedencia
print("Alterando precedencia: ", (a + b) * 2)  # Resultado: 30 (a + b se evalúa primero)

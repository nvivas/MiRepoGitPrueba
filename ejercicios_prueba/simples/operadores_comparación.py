# Definición de variables para comparación
x: int = 10
y: int = 5

# Igualdad (==)
print("x == y: ", x == y)  # Resultado: False

# Desigualdad (!=)
print("x != y: ", x != y)  # Resultado: True

# Mayor que (>)
print("x > y: ", x > y)  # Resultado: True

# Menor que (<)
print("x < y: ", x < y)  # Resultado: False

# Mayor o igual que (>=)
print("x >= y: ", x >= y)  # Resultado: True

# Menor o igual que (<=)
print("x <= y: ", x <= y)  # Resultado: False

# Definición de variables para operadores de pertenencia
lista: list = [1, 2, 3, 4]
cadena: str = "Hola, mundo!"

# Operador de pertenencia (in)
print("2 in lista: ", 2 in lista)  # True, porque 2 está en la lista
print("'Hola' in cadena: ", "Hola" in cadena)  # True, porque 'Hola' está en la cadena

# Operador de no pertenencia (not in)
print("5 not in lista: ", 5 not in lista)  # True, porque 5 no está en la lista
print("'Adiós' not in cadena: ", "Adiós" not in cadena)  # True, porque 'Adiós' no está en la cadena
